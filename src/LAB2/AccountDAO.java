package LAB2;

import LAB1.Account;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;

public class AccountDAO {

    // Connection to the PostgreSQL database.
    private Connection connection;

    // Receive the connection from Main.java.
    public AccountDAO(Connection connection) {
        this.connection = connection;
    }

    // CREATE: Create a wallet or savings account.
    public int createAccount(int customerId, String accountType,
                             double initialBalance) throws SQLException {

        // Check the account type.
        if (accountType == null
                || (!accountType.equalsIgnoreCase("WALLET")
                && !accountType.equalsIgnoreCase("SAVINGS"))) {
            throw new IllegalArgumentException(
                    "Account type must be WALLET or SAVINGS.");
        }

        // An account cannot start with a negative balance.
        if (initialBalance < 0) {
            throw new IllegalArgumentException(
                    "Initial balance cannot be negative.");
        }

        String sql = "INSERT INTO accounts "
                + "(customer_id, account_type, balance) "
                + "VALUES (?, ?, ?)";

        try (PreparedStatement statement =
                     connection.prepareStatement(
                             sql, Statement.RETURN_GENERATED_KEYS)) {

            statement.setInt(1, customerId);
            statement.setString(2, accountType.toUpperCase());
            statement.setDouble(3, initialBalance);

            statement.executeUpdate();

            // Get the new account ID generated by PostgreSQL.
            try (ResultSet result = statement.getGeneratedKeys()) {
                if (result.next()) {
                    return result.getInt(1);
                }
            }
        }

        throw new SQLException("Account could not be created.");
    }

    // READ: Find one account using its ID.
    public Account getAccountById(int accountId) throws SQLException {

        String sql = "SELECT * FROM accounts WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, accountId);

            try (ResultSet result = statement.executeQuery()) {
                if (result.next()) {
                    return mapAccount(result);
                }
            }
        }

        return null;
    }

    // READ: Retrieve all accounts.
    public List<Account> getAllAccounts() throws SQLException {

        List<Account> accounts = new ArrayList<>();

        String sql = "SELECT * FROM accounts ORDER BY id";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql);
             ResultSet result = statement.executeQuery()) {

            while (result.next()) {
                accounts.add(mapAccount(result));
            }
        }

        return accounts;
    }

    // UPDATE: Change the account type.
    public boolean updateAccountType(int accountId, String accountType)
            throws SQLException {

        if (accountType == null
                || (!accountType.equalsIgnoreCase("WALLET")
                && !accountType.equalsIgnoreCase("SAVINGS"))) {
            throw new IllegalArgumentException(
                    "Account type must be WALLET or SAVINGS.");
        }

        String sql = "UPDATE accounts SET account_type = ? WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setString(1, accountType.toUpperCase());
            statement.setInt(2, accountId);

            return statement.executeUpdate() > 0;
        }
    }

    // CUSTOM QUERY: Find accounts belonging to one customer.
    public List<Account> getAccountsByCustomerId(int customerId)
            throws SQLException {

        List<Account> accounts = new ArrayList<>();

        String sql = "SELECT * FROM accounts "
                + "WHERE customer_id = ? ORDER BY id";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, customerId);

            try (ResultSet result = statement.executeQuery()) {
                while (result.next()) {
                    accounts.add(mapAccount(result));
                }
            }
        }

        return accounts;
    }

    // DEPOSIT: Add money to an account.
    public boolean deposit(int accountId, double amount)
            throws SQLException {

        if (amount <= 0) {
            throw new IllegalArgumentException(
                    "Deposit amount must be greater than zero.");
        }

        String sql = "UPDATE accounts "
                + "SET balance = balance + ? WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setDouble(1, amount);
            statement.setInt(2, accountId);

            return statement.executeUpdate() > 0;
        }
    }

    // WITHDRAW: Withdraw money only when the balance is sufficient.
    public boolean withdraw(int accountId, double amount)
            throws SQLException {

        if (amount <= 0) {
            throw new IllegalArgumentException(
                    "Withdrawal amount must be greater than zero.");
        }
//        the balance is reduced only if the account exists and has sufficient funds
        String sql = "UPDATE accounts "
                + "SET balance = balance - ? "
                + "WHERE id = ? AND balance >= ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setDouble(1, amount);
            statement.setInt(2, accountId);
            statement.setDouble(3, amount);

            // Returns false if the account is missing or funds are insufficient.
            return statement.executeUpdate() > 0;
        }
    }

    // DELETE: Delete an inactive account.
    // Here, inactive means zero balance and no transaction history.
    public boolean deleteInactiveAccount(int accountId)
            throws SQLException {

        String sql = "DELETE FROM accounts "
                + "WHERE id = ? "
                + "AND balance = 0 "
                + "AND NOT EXISTS ("
                + "SELECT 1 FROM transactions "
                + "WHERE account_id = accounts.id)";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, accountId);

            return statement.executeUpdate() > 0;
        }
    }

    // Convert one database row into an Account object.
    private Account mapAccount(ResultSet result) throws SQLException {

        Account account = new Account(
                result.getInt("id"),
                result.getInt("customer_id"),
                result.getString("account_type"),
                result.getDouble("balance")
        );

        // Read the creation date from the database.
        Timestamp timestamp = result.getTimestamp("created_at");

        if (timestamp != null) {
            account.setCreatedAt(timestamp.toLocalDateTime());
        }

        return account;
    }
}
