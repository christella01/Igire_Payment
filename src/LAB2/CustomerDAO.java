package LAB2;

import LAB1.Customer;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

public class CustomerDAO {

    // Reuse the database connection provided by Main.java.
    private Connection connection;

    // Constructor: receive the existing database connection.
    public CustomerDAO(Connection connection) {
        this.connection = connection;
    }

    // CREATE: Add a new customer to PostgreSQL.
    public int addCustomer(Customer customer) throws SQLException {

        String sql = "INSERT INTO customers "
                + "(full_name, email, phone_number) "
                + "VALUES (?, ?, ?)";

        try (PreparedStatement statement =
                     connection.prepareStatement(
                             sql, Statement.RETURN_GENERATED_KEYS)) {

            // Set the customer's details in the SQL statement.
            statement.setString(1, customer.getFullName());
            statement.setString(2, customer.getEmail());
            statement.setString(3, customer.getPhoneNumber());

            // Execute the INSERT statement.
            statement.executeUpdate();

            // Get the ID generated by PostgreSQL.
            try (ResultSet result = statement.getGeneratedKeys()) {

                if (result.next()) {
                    int id = result.getInt(1);

                    // Save the generated ID in the Java object.
                    customer.setId(id);

                    return id;
                }
            }
        }

        throw new SQLException("Customer could not be added.");
    }

    // READ: Find one customer using their ID.
    public Customer getCustomerById(int id) throws SQLException {

        String sql = "SELECT id, full_name, email, phone_number "
                + "FROM customers WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, id);

            try (ResultSet result = statement.executeQuery()) {

                if (result.next()) {
                    return new Customer(
                            result.getInt("id"),
                            result.getString("full_name"),
                            result.getString("email"),
                            result.getString("phone_number")
                    );
                }
            }
        }

        // Return null when the customer does not exist.
        return null;
    }

    // READ: Get all customers from PostgreSQL.
    public List<Customer> getAllCustomers() throws SQLException {

        List<Customer> customers = new ArrayList<>();

        String sql = "SELECT id, full_name, email, phone_number "
                + "FROM customers ORDER BY id";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql);
             ResultSet result = statement.executeQuery()) {

            // Read every customer returned by the query.
            while (result.next()) {

                Customer customer = new Customer(
                        result.getInt("id"),
                        result.getString("full_name"),
                        result.getString("email"),
                        result.getString("phone_number")
                );

                customers.add(customer);
            }
        }

        return customers;
    }

    // UPDATE: Change an existing customer's details.
    public boolean updateCustomer(Customer customer)
            throws SQLException {

        String sql = "UPDATE customers "
                + "SET full_name = ?, email = ?, phone_number = ? "
                + "WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setString(1, customer.getFullName());
            statement.setString(2, customer.getEmail());
            statement.setString(3, customer.getPhoneNumber());
            statement.setInt(4, customer.getId());

            // True means at least one customer was updated.
            return statement.executeUpdate() > 0;
        }
    }

    // DELETE: Delete a customer using their ID.
    public boolean deleteCustomer(int id) throws SQLException {

        String sql = "DELETE FROM customers WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, id);

            // True means a customer was deleted.
            return statement.executeUpdate() > 0;
        }
    }

    // CUSTOM QUERY: Search for a customer by email.
    public Customer getCustomerByEmail(String email)
            throws SQLException {

        String sql = "SELECT id, full_name, email, phone_number "
                + "FROM customers WHERE email = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setString(1, email);

            try (ResultSet result = statement.executeQuery()) {

                if (result.next()) {
                    return new Customer(
                            result.getInt("id"),
                            result.getString("full_name"),
                            result.getString("email"),
                            result.getString("phone_number")
                    );
                }
            }
        }

        // Return null when no matching email is found.
        return null;
    }
}