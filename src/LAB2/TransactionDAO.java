package LAB2;

import LAB1.Transaction;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

public class TransactionDAO {

    // Connection to PostgreSQL.
    private Connection connection;

    // Receive the connection from Main.java.
    public TransactionDAO(Connection connection) {
        this.connection = connection;
    }

    // CREATE: Save a transaction in the database.
    public int addTransaction(Transaction transaction)
            throws SQLException {

        validateTransaction(transaction);

        String sql = "INSERT INTO transactions "
                + "(account_id, reference_id, transaction_type, "
                + "amount, created_at) "
                + "VALUES (?, ?, ?, ?, ?)";

        try (PreparedStatement statement =
                     connection.prepareStatement(
                             sql, Statement.RETURN_GENERATED_KEYS)) {

            statement.setInt(1, transaction.getAccountId());
            statement.setString(2, transaction.getReferenceId());
            statement.setString(
                    3, transaction.getTransactionType().toUpperCase());
            statement.setDouble(4, transaction.getAmount());

            // Use the current time if no timestamp was provided.
            LocalDateTime time = transaction.getTimestamp();

            if (time == null) {
                time = LocalDateTime.now();
            }

            statement.setTimestamp(5, Timestamp.valueOf(time));

            statement.executeUpdate();

            // Read the transaction ID generated by PostgreSQL.
            try (ResultSet result = statement.getGeneratedKeys()) {
                if (result.next()) {
                    int id = result.getInt(1);
                    transaction.setTransactionId(id);
                    return id;
                }
            }
        }

        throw new SQLException("Transaction could not be saved.");
    }

    // READ: Find a transaction using its ID.
    public Transaction getTransactionById(int id)
            throws SQLException {

        String sql = "SELECT * FROM transactions WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, id);

            try (ResultSet result = statement.executeQuery()) {
                if (result.next()) {
                    return mapTransaction(result);
                }
            }
        }

        return null;
    }

    // READ: Retrieve all transaction records.
    public List<Transaction> getAllTransactions()
            throws SQLException {

        List<Transaction> transactions = new ArrayList<>();

        String sql = "SELECT * FROM transactions ORDER BY id";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql);
             ResultSet result = statement.executeQuery()) {

            while (result.next()) {
                transactions.add(mapTransaction(result));
            }
        }

        return transactions;
    }

    // UPDATE: Update an existing transaction record.
    public boolean updateTransaction(Transaction transaction)
            throws SQLException {

        validateTransaction(transaction);

        String sql = "UPDATE transactions "
                + "SET account_id = ?, reference_id = ?, "
                + "transaction_type = ?, amount = ?, created_at = ? "
                + "WHERE id = ?";

        LocalDateTime time = transaction.getTimestamp();

        if (time == null) {
            time = LocalDateTime.now();
        }

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, transaction.getAccountId());
            statement.setString(2, transaction.getReferenceId());
            statement.setString(
                    3, transaction.getTransactionType().toUpperCase());
            statement.setDouble(4, transaction.getAmount());
            statement.setTimestamp(5, Timestamp.valueOf(time));
            statement.setInt(6, transaction.getTransactionId());

            return statement.executeUpdate() > 0;
        }
    }

    // DELETE: Delete a transaction record by ID.
    // Use this only for authorized corrections or test cleanup.
    public boolean deleteTransaction(int id) throws SQLException {

        String sql = "DELETE FROM transactions WHERE id = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, id);

            return statement.executeUpdate() > 0;
        }
    }

    // CUSTOM QUERY: Get the transaction history for one account.
    public List<Transaction> getTransactionsByAccountId(int accountId)
            throws SQLException {

        List<Transaction> transactions = new ArrayList<>();

        String sql = "SELECT * FROM transactions "
                + "WHERE account_id = ? ORDER BY id";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setInt(1, accountId);

            try (ResultSet result = statement.executeQuery()) {
                while (result.next()) {
                    transactions.add(mapTransaction(result));
                }
            }
        }

        return transactions;
    }

    // Check the transaction details before saving or updating.
    private void validateTransaction(Transaction transaction) {

        if (transaction == null) {
            throw new IllegalArgumentException(
                    "Transaction cannot be null.");
        }

        String referenceId = transaction.getReferenceId();

        if (referenceId == null
                || referenceId.trim().isEmpty()
                || referenceId.trim().length() > 100) {
            throw new IllegalArgumentException(
                    "Reference ID must contain 1 to 100 characters.");
        }

        if (transaction.getAmount() <= 0) {
            throw new IllegalArgumentException(
                    "Transaction amount must be greater than zero.");
        }

        String type = transaction.getTransactionType();

        if (type == null
                || (!type.equalsIgnoreCase("DEPOSIT")
                && !type.equalsIgnoreCase("WITHDRAWAL")
                && !type.equalsIgnoreCase("TRANSFER"))) {
            throw new IllegalArgumentException(
                    "Transaction type is invalid.");
        }
    }

    // Convert a PostgreSQL row into a Java Transaction object.
    private Transaction mapTransaction(ResultSet result)
            throws SQLException {

        Timestamp timestamp = result.getTimestamp("created_at");

        LocalDateTime time = timestamp == null
                ? null
                : timestamp.toLocalDateTime();

        return new Transaction(
                result.getInt("id"),
                result.getInt("account_id"),
                result.getString("reference_id"),
                result.getDouble("amount"),
                result.getString("transaction_type"),
                time
        );
    }
}